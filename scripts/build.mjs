import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const read = (file) => readFile(new URL(file, root), 'utf8');
const manifest = JSON.parse(await read('package.json'));
const shared = (await read('shared.js')).replace(/^export /gm, '');
const source = (await read('src/client.js')).replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
const preview = (await read('src/preview.js')).replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '');
const styles = await read('src/styles.css') + '\n' + await read('src/preview.css');
const dictionaries = {};
for (const language of ['zh', 'en']) dictionaries[language] = JSON.parse(await read('locale/' + language + '.json')).ui;
const output = '// Generated by scripts/build.mjs; edit src/client.js, src/styles.css or shared.js.\n' +
  'window.__ModuleLoader__.load({ id: ' + JSON.stringify(manifest.name) + ', factory(require) {\n' +
  shared + '\n' + preview + '\n' + source + '\nreturn createPlugin(require("react"), ' + JSON.stringify({styles, dictionaries}) + ');\n} });\n';
await writeFile(new URL('client.js', root), output);
console.log('Built ' + fileURLToPath(new URL('client.js', root)) + ' (' + Buffer.byteLength(output) + ' bytes)');
